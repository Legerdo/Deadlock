/** Rooms that still hold a required clue the player has not collected. */
export function remainingLeadRooms(ctx: StoryContext): string[] {
  const rooms = new Set<RoomId>();
  for (const id of REQUIRED_EVIDENCE) {
    if (ctx.evidence.has(id)) continue;
    rooms.add(EVIDENCE_BY_ID.get(id)!.obtainedAt);
  }
  return [...rooms].map((r) => ROOMS[r].name);
}

