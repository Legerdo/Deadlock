function lockAll(text: string) {
  return { ARRIVAL: text, DINNER: text, EVENING: text, INCIDENT: text, INVESTIGATION: text, PRE_HEARING: text, EPILOGUE: text } as const;
}

export const ROOM_IDS = Object.keys(ROOMS) as RoomId[];

/** Undirected room graph derived from door data. */
export function roomGraph(): Map<RoomId, Set<RoomId>> {
  const g = new Map<RoomId, Set<RoomId>>();
  for (const id of ROOM_IDS) g.set(id, new Set());
  for (const r of Object.values(ROOMS)) for (const d of r.doors) if (d.to) g.get(r.id)!.add(d.to);
  return g;
}
